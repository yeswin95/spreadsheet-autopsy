import type { Report } from './analyze';
import { formatDelimiter, formatNumber, formatPercent } from './format';

function cell(value: string): string {
  const flat = value.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
  if (flat.length <= 60) return flat;
  return `${flat.slice(0, 57)}…`;
}

const SEVERITY_ORDER = { high: 0, medium: 1, low: 2 } as const;

export function toMarkdown(report: Report): string {
  const sorted = [...report.issues].sort(
    (a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity],
  );

  const lines: string[] = [];
  lines.push(`# Spreadsheet Autopsy — ${report.file}`);
  lines.push('');
  lines.push(
    `**Health score:** ${report.score}/100 (${report.grade}) · **Rows:** ${formatNumber(
      report.rows,
    )} · **Columns:** ${report.columns} · **Delimiter:** ${formatDelimiter(report.delimiter)}`,
  );
  lines.push('');

  lines.push('## What to fix first');
  lines.push('');
  if (sorted.length === 0) {
    lines.push('No problems were detected.');
  } else {
    sorted.forEach((issue, index) => {
      const where = issue.column ? `**${issue.column} — ` : '**';
      const close = issue.column ? '**' : '**';
      lines.push(`${index + 1}. ${issue.severity.toUpperCase()} · ${where}${issue.title}${close} — ${issue.detail}`);
    });
  }
  lines.push('');

  lines.push('## Column report');
  lines.push('');
  lines.push('| Column | Type | Blank | Distinct | Issues |');
  lines.push('| --- | --- | ---: | ---: | ---: |');
  for (const profile of report.profiles) {
    lines.push(
      `| ${cell(profile.name)} | ${profile.kind} | ${formatPercent(
        profile.blanks,
        profile.total,
      )} | ${formatNumber(profile.unique)} | ${profile.issues.length} |`,
    );
  }
  lines.push('');

  lines.push('## Data preview');
  lines.push('');
  if (report.preview.length > 0) {
    lines.push(`| ${report.headers.map(cell).join(' | ')} |`);
    lines.push(`| ${report.headers.map(() => '---').join(' | ')} |`);
    for (const row of report.preview.slice(0, 5)) {
      lines.push(`| ${report.headers.map((_, index) => cell(row[index] ?? '')).join(' | ')} |`);
    }
    lines.push('');
    lines.push(`_First ${Math.min(5, report.preview.length)} of ${formatNumber(report.rows)} rows._`);
  } else {
    lines.push('No data rows.');
  }
  lines.push('');

  lines.push('---');
  lines.push('Generated by Spreadsheet Autopsy. The file never left this browser.');

  return `${lines.join('\n')}\n`;
}

export function toJson(report: Report): string {
  return `${JSON.stringify(report, null, 2)}\n`;
}

export function downloadText(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}
